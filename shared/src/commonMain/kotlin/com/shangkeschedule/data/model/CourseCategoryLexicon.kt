package com.shangkeschedule.data.model

/**
 * 课程性质词表（v4.75.0）。
 *
 * 用途：把「粘贴进来的教务文本」里的课程性质认出来。此前粘贴导入完全不解析性质，
 * 导入的成绩 100% 落进「未分类」，学业情况页因此只剩一行「未分类」，
 * 看起来就像「只统计总门数、不统计具体分类」。
 *
 * 刻意用**整词精确匹配**而不是 `startsWith` / 正则包含：
 * 性质在粘贴文本里是**独立的分隔符切分出来的 token**（如「高等数学 必修 5 92」），
 * 用包含式匹配会把「专业英语」「基础会计」这类课程名的一部分误当性质。
 *
 * 与适配脚本侧的类别处理**不冲突**：脚本从学校页面读原始类别名（如「通识教育课程平台/必修」），
 * 属于「本校原文」，不经过本词表；本词表只服务本地粘贴解析这条兜底路径。
 */
object CourseCategoryLexicon {

    /** 完整匹配才认的性质词。 */
    val WORDS: Set<String> = setOf(
        // 常见两级写法
        "必修", "选修", "限选", "任选", "公选", "通识",
        "必修课", "选修课", "限选课", "任选课", "公选课", "通识课",
        // 带前缀的完整写法（学校导出常见）
        "专业必修", "专业选修", "公共必修", "公共选修", "通识必修", "通识选修",
        "专业必修课", "专业选修课", "公共必修课", "公共选修课",
        // 培养方案里的模块名
        "学科基础", "专业核心", "专业方向", "实践环节", "集中实践",
        "公共基础", "通识教育", "创新创业", "素质拓展"
    )

    /** 去掉包裹符号后是否为性质词。 */
    fun matches(token: String?): Boolean {
        val trimmed = token?.trim()?.trim('：', ':', '（', '(', '）', ')', '【', '】', '[', ']', '·', '、')
            ?: return false
        return trimmed.isNotEmpty() && trimmed in WORDS
    }

    /** 在一组候选里挑出第一个性质词。 */
    fun firstMatch(tokens: Iterable<String>): String? =
        tokens.firstOrNull { matches(it) }?.trim()
}
